export function connectionStateLabel(
  state: "not_configured" | "local_adapter_ready" | "connection_not_verified" | "disabled",
): string {
  switch (state) {
    case "not_configured":
      return CONNECTIONS.notConfigured;
    case "local_adapter_ready":
      return CONNECTIONS.localAdapterReady;
    case "connection_not_verified":
      return CONNECTIONS.connectionNotVerified;
    case "disabled":
      return CONNECTIONS.disabled;
  }
}

