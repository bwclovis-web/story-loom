const plural = (n: number, one: string, many = `${one}s`) => `${n.toLocaleString("en-US")} ${n === 1 ? one : many}`;

/** The parts of a tidy report worth telling the author, in reading order. */
export function tidySummary(r: TidyReport): string[] {
  return [
    r.blankLines ? `${plural(r.blankLines, "extra blank line")} removed` : "",
    r.trailingSpaces ? `trailing spaces on ${plural(r.trailingSpaces, "line")}` : "",
    r.headings ? plural(r.headings, "heading") : "",
    r.sceneBreaks ? plural(r.sceneBreaks, "scene break") : "",
    r.spacing ? `${plural(r.spacing, "blank line")} added around headings and scene breaks` : "",
    r.quotes ? plural(r.quotes, "quote mark") : "",
    r.dashes ? plural(r.dashes, "dash", "dashes") : "",
    r.ellipses ? plural(r.ellipses, "ellipsis", "ellipses") : "",
  ].filter(Boolean);
}

